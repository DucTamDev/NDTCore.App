/**
 * `text` → mảng byte CP1258. Ký tự không nằm trong `PRECOMPOSED`: `< 0x80` giữ
 * nguyên (ASCII trùng CP1258); `0x80–0xFF` giữ nguyên byte thấp (dải này của
 * CP1258 phần lớn trùng Latin-1 — các slot bị đổi nghĩa đã được `PRECOMPOSED`
 * xử lý trước); ngoài dải → `?` (0x3f).
 */
export const encodeCp1258 = (text: string): number[] => {
  const bytes: number[] = [];
  for (const char of text) {
    const mapped = PRECOMPOSED[char];
    if (mapped) {
      bytes.push(...mapped);
      continue;
    }
    const codePoint = char.codePointAt(0) ?? 0;
    bytes.push(codePoint <= LATIN1_MAX ? codePoint : QUESTION_MARK);
  }
  return bytes;
};
