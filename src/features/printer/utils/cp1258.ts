/**
 * Encode chuỗi tiếng Việt sang byte Windows-1258 (CP1258) — dùng cho lệnh
 * `TEXT` của TSPL khi máy in được cấu hình `renderMode: 'internalfont'` với
 * `codepage: '1258'` (font nội bộ của máy in tự vẽ glyph, không phải bitmap).
 *
 * CP1258 là bảng mã "lai": phần lớn ký tự có dấu mũ/breve/móc (â ă ê ô ơ ư đ)
 * nằm gọn trong 1 byte, nhưng 5 dấu thanh (huyền/sắc/ngã/hỏi/nặng) là byte
 * TỔ HỢP đứng SAU byte ký tự nền. Bảng `PRECOMPOSED` dưới đây đã ưu tiên slot
 * 1-byte của CP1258 khi có (chạy được cả trên firmware bỏ qua byte tổ hợp),
 * chỉ rơi về "nền + thanh" cho các tổ hợp CP1258 không có sẵn 1 byte.
 *
 * `iconv-lite` (`windows-1258`) KHÔNG dùng được ở đây vì codec của nó thay các
 * tổ hợp bằng `?` thay vì phát byte thanh tổ hợp.
 *
 * Bảng `PRECOMPOSED` được sinh OFFLINE rồi nhúng tĩnh — KHÔNG gọi `normalize`
 * lúc chạy vì Hermes (RN 0.86) có thể build không kèm ICU. Cách sinh lại: với
 * mỗi ký tự tiếng Việt tiền tổ hợp (dải U+00C0–U+00FF, U+0102/0103, U+0110/0111,
 * U+0128/0129, U+0168/0169, U+01A0/01A1, U+01AF/01B0, U+1EA0–U+1EF9), NFD-tách
 * → nếu CP1258 có slot 1 byte cho ký tự đó thì dùng luôn, ngược lại ghép
 * `[byte nền, byte thanh tổ hợp]` (nền tra từ dạng NFC không dấu thanh, thanh
 * tra từ `{huyền:0xCC, sắc:0xEC, ngã:0xDE, hỏi:0xD2, nặng:0xF2}`).
 */
